// Installs a desktop launcher so Checkarr can be started from the app drawer
// instead of a terminal: a .app bundle on macOS (Launchpad / Applications), a
// .desktop entry on Linux, a Start-menu shortcut on Windows. One icon, one
// job: start the server if it is not already up, then open the dashboard.
//
// Everything is written under the user's home directory - no admin rights.
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { downsample, encodeIco, encodePng, renderIcon } from "./icon.mjs";

export const APP_NAME = "Checkarr";

const STANDARD_PATH = ["/usr/local/bin", "/usr/bin", "/bin", "/usr/sbin", "/sbin"];

// Where a standalone (non-npm-global) pnpm lives. The launcher's PATH must
// include these, because a Finder-launched app does not inherit the shell's
// PATH; a first launch that needs a build runs pnpm from here.
const pnpmPathEntries = (home) => [
  path.join(home, "Library", "pnpm"),
  path.join(home, ".local", "share", "pnpm"),
  "/opt/homebrew/bin"
];

// The .icns is expensive to build, so it is only rebuilt when the renderer
// changes. This hash covers scripts/lib/icon.mjs in full.
const ICON_SOURCE = path.join(import.meta.dirname, "icon.mjs");

export function desktopPaths(platform, home, env = {}) {
  if (platform === "darwin") {
    return { appPath: path.join(home, "Applications", `${APP_NAME}.app`) };
  }
  if (platform === "linux") {
    const share = env.XDG_DATA_HOME || path.join(home, ".local", "share");
    return {
      desktopFile: path.join(share, "applications", "checkarr.desktop"),
      iconPath: path.join(share, "icons", "hicolor", "256x256", "apps", "checkarr.png")
    };
  }
  if (platform === "win32") {
    const appData = env.APPDATA || path.join(home, "AppData", "Roaming");
    const localAppData = env.LOCALAPPDATA || path.join(home, "AppData", "Local");
    return {
      lnkPath: path.join(appData, "Microsoft", "Windows", "Start Menu", "Programs", `${APP_NAME}.lnk`),
      icoPath: path.join(localAppData, APP_NAME, "checkarr.ico")
    };
  }
  throw new Error(`unsupported platform for the desktop icon: ${platform}`);
}

function writeFileEnsured(file, data, mode) {
  const wanted = Buffer.isBuffer(data) ? data : Buffer.from(data);
  let current = null;
  try {
    current = fs.readFileSync(file);
  } catch {}
  let changed = false;
  if (!current || !current.equals(wanted)) {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, wanted, mode == null ? undefined : { mode });
    changed = true;
  }
  if (mode != null) {
    const actual = fs.statSync(file).mode & 0o777;
    if (actual !== mode) {
      fs.chmodSync(file, mode);
      changed = true;
    }
  }
  return changed;
}

function readVersion(root) {
  try {
    return JSON.parse(fs.readFileSync(path.join(root, "package.json"), "utf8")).version ?? "0.0.0";
  } catch {
    return "0.0.0";
  }
}

function readPort(options, env) {
  const raw = options.port ?? env.CHECKARR_PORT ?? env.PORT;
  if (raw == null || raw === "") return null;
  const port = Number(raw);
  if (!Number.isInteger(port) || port <= 0 || port > 65535) throw new Error(`invalid port: ${raw}`);
  return port;
}

/** Quote a value for use inside a POSIX shell script. */
const sh = (value) => `"${String(value).replace(/(["\\$`])/g, "\\$1")}"`;

/** The executable inside Checkarr.app: find Node, then run the launcher. */
export function launcherExecutable({ launch, node, home, port }) {
  const nodeDir = path.dirname(node);
  const pathEntries = [...new Set([nodeDir, ...pnpmPathEntries(home), ...STANDARD_PATH])];
  return [
    "#!/bin/sh",
    '# Generated by scripts/desktop.mjs. Re-run "pnpm app:install" from the',
    "# Checkarr checkout after moving it, switching Node, or editing the launcher.",
    `export PATH=${sh(pathEntries.join(path.delimiter))}`,
    ...(port == null ? [] : ["", `[ -n "$CHECKARR_PORT" ] || export CHECKARR_PORT=${sh(port)}`]),
    "",
    `NODE=${sh(node)}`,
    `LAUNCH=${sh(launch)}`,
    'if [ ! -x "$NODE" ]; then NODE="$(command -v node 2>/dev/null || true)"; fi',
    'if [ ! -x "$NODE" ]; then',
    '  /usr/bin/osascript -e \'display alert "Checkarr" message "Node.js was not found. Run pnpm app:install from the Checkarr folder again." as critical\' >/dev/null 2>&1',
    "  exit 1",
    "fi",
    'if [ ! -f "$LAUNCH" ]; then',
    '  /usr/bin/osascript -e \'display alert "Checkarr" message "The Checkarr launcher moved. Run pnpm app:install from its new folder." as critical\' >/dev/null 2>&1',
    "  exit 1",
    "fi",
    'exec "$NODE" "$LAUNCH" "$@"',
    ""
  ].join("\n");
}

export function macInfoPlist({ version }) {
  return `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
\t<key>CFBundleDevelopmentRegion</key>
\t<string>en</string>
\t<key>CFBundleDisplayName</key>
\t<string>${APP_NAME}</string>
\t<key>CFBundleExecutable</key>
\t<string>${APP_NAME}</string>
\t<key>CFBundleIconFile</key>
\t<string>${APP_NAME}</string>
\t<key>CFBundleIdentifier</key>
\t<string>local.checkarr.launcher</string>
\t<key>CFBundleInfoDictionaryVersion</key>
\t<string>6.0</string>
\t<key>CFBundleName</key>
\t<string>${APP_NAME}</string>
\t<key>CFBundlePackageType</key>
\t<string>APPL</string>
\t<key>CFBundleShortVersionString</key>
\t<string>${version}</string>
\t<key>CFBundleVersion</key>
\t<string>${version}</string>
\t<key>LSMinimumSystemVersion</key>
\t<string>10.15</string>
\t<key>LSUIElement</key>
\t<true/>
\t<key>NSHighResolutionCapable</key>
\t<true/>
</dict>
</plist>
`;
}

export function linuxDesktopEntry({ launch, node, iconPath, home, port }) {
  const pathEntries = [...new Set([path.dirname(node), ...pnpmPathEntries(home), ...STANDARD_PATH])];
  const env = [
    "/usr/bin/env",
    `PATH="${pathEntries.join(path.delimiter)}"`,
    ...(port == null ? [] : [`CHECKARR_PORT=${port}`]),
    `"${node}"`,
    `"${launch}"`
  ];
  return `[Desktop Entry]
Type=Application
Version=1.0
Name=${APP_NAME}
GenericName=Media integrity checker
Comment=Verify that Radarr/Sonarr media files actually play
Exec=${env.join(" ")}
Icon=${iconPath}
Terminal=false
Categories=AudioVideo;Video;Utility;
StartupNotify=true
`;
}

/** PowerShell that creates the Start-menu shortcut for a Windows install. */
export function windowsShortcutScript({ lnkPath, target, args, workdir, iconPath }) {
  const ps = (value) => String(value).replace(/'/g, "''");
  return [
    "$ws = New-Object -ComObject WScript.Shell",
    `$sc = $ws.CreateShortcut('${ps(lnkPath)}')`,
    `$sc.TargetPath = '${ps(target)}'`,
    `$sc.Arguments = '${ps(args)}'`,
    `$sc.WorkingDirectory = '${ps(workdir)}'`,
    `$sc.IconLocation = '${ps(iconPath)}'`,
    `$sc.Description = 'Checkarr media integrity checker'`,
    "$sc.Save()"
  ].join("\n");
}

function writeMacIcon(iconPath, run) {
  const master = renderIcon(1024);
  const pngs = new Map();
  const pngFor = (size) => {
    let png = pngs.get(size);
    if (!png) {
      png = encodePng(size === 1024 ? master : downsample(master, 1024, size), size);
      pngs.set(size, png);
    }
    return png;
  };
  // iconutil only accepts a directory whose name ends in ".iconset".
  const work = fs.mkdtempSync(path.join(os.tmpdir(), "checkarr-iconset-"));
  const iconset = path.join(work, APP_NAME + ".iconset");
  fs.mkdirSync(iconset);
  try {
    const entries = [
      ["icon_16x16.png", 16],
      ["icon_16x16@2x.png", 32],
      ["icon_32x32.png", 32],
      ["icon_32x32@2x.png", 64],
      ["icon_128x128.png", 128],
      ["icon_128x128@2x.png", 256],
      ["icon_256x256.png", 256],
      ["icon_256x256@2x.png", 512],
      ["icon_512x512.png", 512],
      ["icon_512x512@2x.png", 1024]
    ];
    for (const [name, size] of entries) fs.writeFileSync(path.join(iconset, name), pngFor(size));
    fs.mkdirSync(path.dirname(iconPath), { recursive: true });
    run("iconutil", ["-c", "icns", iconset, "-o", iconPath]);
  } finally {
    fs.rmSync(work, { recursive: true, force: true });
  }
}

function iconSourceHash() {
  return createHash("sha256").update(fs.readFileSync(ICON_SOURCE)).digest("hex");
}

/**
 * Create (or refresh) the desktop launcher for this checkout. Idempotent:
 * files are only rewritten when their content actually changed.
 */
export async function ensureDesktopApp(options = {}) {
  const platform = options.platform ?? process.platform;
  const home = options.home ?? os.homedir();
  const env = options.env ?? process.env;
  const root = options.root ?? path.resolve(import.meta.dirname, "..", "..");
  const node = options.node ?? process.execPath;
  const version = options.version ?? readVersion(root);
  const run =
    options.run ??
    ((cmd, args) => {
      try {
        execFileSync(cmd, args, { stdio: ["ignore", "ignore", "pipe"], windowsHide: true });
      } catch (err) {
        const detail = err.stderr ? err.stderr.toString().trim() : err.message;
        throw new Error(`${cmd} failed: ${detail}`, { cause: err });
      }
    });
  const port = readPort(options, env);
  const launch = path.join(root, "scripts", "launch.mjs");

  const paths = desktopPaths(platform, home, env);
  if (platform === "darwin") {
    const contents = path.join(paths.appPath, "Contents");
    let updated = writeFileEnsured(path.join(contents, "Info.plist"), macInfoPlist({ version }));
    updated = writeFileEnsured(path.join(contents, "PkgInfo"), "APPL????") || updated;
    updated =
      writeFileEnsured(
        path.join(contents, "MacOS", APP_NAME),
        launcherExecutable({ launch, node, home, port }),
        0o755
      ) || updated;

    const iconPath = path.join(contents, "Resources", `${APP_NAME}.icns`);
    const stampPath = path.join(contents, "Resources", ".icon-source");
    let stamp = null;
    try {
      stamp = fs.readFileSync(stampPath, "utf8");
    } catch {}
    if (!fs.existsSync(iconPath) || stamp !== iconSourceHash()) {
      writeMacIcon(iconPath, run);
      fs.writeFileSync(stampPath, iconSourceHash());
      updated = true;
    }
    return { platform, target: paths.appPath, updated };
  }

  if (platform === "linux") {
    const icon = renderIcon(256);
    writeFileEnsured(paths.iconPath, encodePng(icon, 256));
    const updated = writeFileEnsured(
      paths.desktopFile,
      linuxDesktopEntry({ launch, node, iconPath: paths.iconPath, home, port }),
      0o755
    );
    return { platform, target: paths.desktopFile, updated };
  }

  // win32
  const icon = encodeIco(encodePng(renderIcon(256), 256));
  writeFileEnsured(paths.icoPath, icon);
  run("powershell", [
    "-NoProfile",
    "-NonInteractive",
    "-Command",
    windowsShortcutScript({
      lnkPath: paths.lnkPath,
      target: node,
      args: `"${launch}"`,
      workdir: root,
      iconPath: paths.icoPath
    })
  ]);
  return { platform, target: paths.lnkPath, updated: true };
}

/** Remove the desktop launcher installed by ensureDesktopApp. */
export async function removeDesktopApp(options = {}) {
  const platform = options.platform ?? process.platform;
  const home = options.home ?? os.homedir();
  const env = options.env ?? process.env;
  const paths = desktopPaths(platform, home, env);
  const targets =
    platform === "darwin"
      ? [paths.appPath]
      : platform === "linux"
        ? [paths.desktopFile, paths.iconPath]
        : [paths.lnkPath, path.dirname(paths.icoPath)];
  const removed = [];
  for (const target of targets) {
    if (!fs.existsSync(target)) continue;
    fs.rmSync(target, { recursive: true, force: true });
    removed.push(target);
  }
  return { platform, removed };
}
