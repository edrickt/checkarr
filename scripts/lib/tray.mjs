// Keeps a Checkarr icon in the menu bar (macOS), the notification area
// (Windows), or a status notifier (Linux) while the app runs: click it to
// open the dashboard, read the log, or stop everything. The host process is
// spawned detached, so the terminal that ran `pnpm start` can be closed.
//
// One host per platform, all carrying "checkarr-tray" in their path - that
// marker is how a pid from a stale file is told apart from a recycled pid:
//   macOS    osascript -l JavaScript, an NSStatusBar item (template image)
//   Windows  a PowerShell WinForms NotifyIcon behind a hidden .vbs shim
//   Linux    yad --notification, when yad is installed
import { execFileSync, execSync, spawn } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { APP_NAME } from "./desktop.mjs";
import { encodePng, renderGlyph } from "./icon.mjs";

export const TRAY_MARKER = "checkarr-tray";

const rootFromHere = () => path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");

/** Where the tray host, its icon, and its pid file live. */
export function trayPaths(options = {}) {
  const platform = options.platform ?? process.platform;
  const home = options.home ?? os.homedir();
  const env = options.env ?? process.env;
  const root = options.root ?? rootFromHere();
  // The platform is explicit, so Windows paths must not pick up the host's
  // separator when this runs from a POSIX machine (tests, WSL-style hosts).
  const join = platform === "win32" ? path.win32.join : path.join;
  const data = join(root, "data");
  const base = {
    root,
    data,
    pidFile: join(data, "checkarr-tray.pid"),
    logFile: join(data, "tray.log")
  };
  if (platform === "darwin") {
    return {
      ...base,
      iconFile: join(data, "checkarr-tray.png"),
      scriptFile: join(data, "checkarr-tray.jxa.js")
    };
  }
  if (platform === "linux") {
    return { ...base, iconFile: join(data, "checkarr-tray.png") };
  }
  if (platform === "win32") {
    const localAppData = env.LOCALAPPDATA || join(home, "AppData", "Local");
    const store = join(localAppData, TRAY_MARKER);
    return {
      ...base,
      store,
      iconFile: join(store, "tray.png"),
      scriptFile: join(store, "CheckarrTray.ps1"),
      launcherFile: join(store, "CheckarrTray.vbs")
    };
  }
  throw new Error(`unsupported platform for the tray icon: ${platform}`);
}

function writeIfChanged(file, data) {
  const wanted = Buffer.isBuffer(data) ? data : Buffer.from(data);
  try {
    if (fs.readFileSync(file).equals(wanted)) return false;
  } catch {}
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, wanted);
  return true;
}

function ensureLog(file) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.closeSync(fs.openSync(file, "a"));
}

/** Single-quote a value for a POSIX shell. */
const shellQuote = (value) => `"${String(value).replace(/(["\\$`])/g, "\\$1")}"`;

/** Double a value's quotes for a PowerShell single-quoted string. */
const psQuote = (value) => `'${String(value).replace(/'/g, "''")}'`;

/**
 * The macOS menu-bar item, as JXA source. Everything is inlined: the icon
 * loads from a file, and each menu action is one shell command. Setting
 * CHECKARR_TRAY_SELFTEST=all makes the actions log instead of run and exits
 * after "clicking" every menu item, which is how the wiring is exercised
 * without a mouse.
 */
export function macTrayScript(config) {
  return `// Checkarr menu-bar icon. Generated by scripts/lib/tray.mjs - do not edit.
ObjC.import('Cocoa');
ObjC.import('stdlib');

const CFG = ${JSON.stringify(config, null, 2)};

function envVar(name) {
  const value = $.NSProcessInfo.processInfo.environment.objectForKey(name);
  return value ? ObjC.unwrap(value) : '';
}
// Selftest "clicks" every menu item and logs the commands instead of running
// them, then exits: how the AppKit wiring is exercised without a mouse.
const SELFTEST = envVar('CHECKARR_TRAY_SELFTEST') === 'all';

function append(line) {
  try {
    const handle = $.NSFileHandle.fileHandleForWritingAtPath(CFG.logFile);
    handle.seekToEndOfFile;
    handle.writeData($.NSString.stringWithString('[' + new Date().toISOString() + '] ' + line + '\\n').dataUsingEncoding($.NSUTF8StringEncoding));
    handle.closeFile;
  } catch (err) {}
}

function shSync(command) {
  const task = $.NSTask.alloc.init;
  task.setLaunchPath('/bin/sh');
  task.setArguments(['-c', command]);
  const pipe = $.NSPipe.pipe;
  task.setStandardOutput(pipe);
  task.setStandardError(pipe);
  task.launch;
  const data = pipe.fileHandleForReading.readDataToEndOfFile;
  task.waitUntilExit;
  const out = ObjC.unwrap($.NSString.alloc.initWithDataEncoding(data, $.NSUTF8StringEncoding));
  return { status: task.terminationStatus, out: out || '' };
}

function run(command) {
  if (SELFTEST) {
    append('selftest: would run ' + command);
    return;
  }
  const task = $.NSTask.alloc.init;
  task.setLaunchPath('/bin/sh');
  task.setArguments(['-c', command]);
  task.setStandardOutput($.NSFileHandle.fileHandleWithNullDevice);
  task.setStandardError($.NSFileHandle.fileHandleWithNullDevice);
  task.launch;
}

const shq = (value) => "'" + String(value).replace(/'/g, "'\\\\''") + "'";

function serverPid() {
  const text = shSync('/bin/cat ' + shq(CFG.pidFile) + ' 2>/dev/null').out.trim();
  const pid = parseInt(text, 10);
  return Number.isFinite(pid) && pid > 0 ? pid : 0;
}

function serverAlive() {
  const pid = serverPid();
  return pid > 0 && shSync('/bin/kill -0 ' + pid + ' 2>/dev/null').status === 0;
}

function remove(file) {
  try {
    $.NSFileManager.defaultManager.removeItemAtPathError(file, null);
  } catch (err) {}
}

function openDashboard() {
  if (serverAlive()) {
    run('/usr/bin/open ' + shq(CFG.url));
    return;
  }
  append('server is stopped - launching it');
  run(shq(CFG.node) + ' ' + shq(CFG.launch));
}

function openLog() {
  run('/usr/bin/open ' + shq(CFG.serverLog));
}

function stopEverything() {
  const pid = serverPid();
  if (pid > 0 && serverAlive()) {
    append('stopping server (pid ' + pid + ')');
    shSync('/bin/kill -TERM ' + pid + ' 2>/dev/null');
  }
  remove(CFG.pidFile);
  remove(CFG.trayPidFile);
  $.exit(0);
}

const app = $.NSApplication.sharedApplication;
app.setActivationPolicy($.NSApplicationActivationPolicyAccessory);

const menu = $.NSMenu.alloc.init;
menu.setAutoenablesItems(false);

ObjC.registerSubclass({
  name: 'CheckarrTrayTarget',
  methods: {
    'openDashboard:': { types: ['void', ['id']], implementation: openDashboard },
    'openLog:': { types: ['void', ['id']], implementation: openLog },
    'stopEverything:': { types: ['void', ['id']], implementation: stopEverything },
    'tick:': {
      types: ['void', ['id']],
      implementation: function () {
        item.button.setToolTip(CFG.label + (serverAlive() ? ' - running' : ' - stopped'));
      }
    },
    'selftest:': {
      types: ['void', ['id']],
      implementation: function () {
        append('selftest: menu has ' + menu.numberOfItems + ' items');
        for (let i = 0; i < menu.numberOfItems; i++) {
          const entry = menu.itemAtIndex(i);
          if (!entry.isSeparatorItem) {
            append('selftest: clicking ' + ObjC.unwrap(entry.title));
            menu.performActionForItemAtIndex(i);
          }
        }
        append('selftest: done');
        $.exit(0);
      }
    }
  }
});
const target = $.CheckarrTrayTarget.alloc.init;

const addItem = (title, action) => {
  const entry = $.NSMenuItem.alloc.initWithTitleActionKeyEquivalent(title, action, '');
  entry.setTarget(target);
  menu.addItem(entry);
};
addItem('Open ' + CFG.label, 'openDashboard:');
addItem('Open log', 'openLog:');
menu.addItem($.NSMenuItem.separatorItem);
addItem('Stop ' + CFG.label, 'stopEverything:');

const image = $.NSImage.alloc.initWithContentsOfFile(CFG.iconFile);
if (image) {
  image.setSize($.NSMakeSize(18, 18));
  image.setTemplate(true);
}
const item = $.NSStatusBar.systemStatusBar.statusItemWithLength($.NSVariableStatusItemLength);
if (image) item.button.setImage(image);
else item.button.setTitle(CFG.label);
item.button.setToolTip(CFG.label + (serverAlive() ? ' - running' : ' - stopped'));
item.setMenu(menu);

// A second host for the same checkout would park a duplicate icon, so leave
// when the recorded pid is still alive (and is not this process).
const existing = parseInt(shSync('/bin/cat ' + shq(CFG.trayPidFile) + ' 2>/dev/null').out.trim(), 10);
if (existing > 0 && existing !== $.NSProcessInfo.processInfo.processIdentifier && shSync('/bin/kill -0 ' + existing + ' 2>/dev/null').status === 0) {
  append('another tray is already running (pid ' + existing + ') - exiting');
  $.exit(0);
}
$.NSString.stringWithString(String($.NSProcessInfo.processInfo.processIdentifier)).writeToFileAtomicallyEncodingError(CFG.trayPidFile, true, $.NSUTF8StringEncoding, null);
append('tray started (pid ' + $.NSProcessInfo.processInfo.processIdentifier + ')');

// Hold every Objective-C object that must outlive this function: JXA's
// bridge does not keep unreferenced proxies alive.
let ticker = null;
if (SELFTEST) ticker = $.NSTimer.scheduledTimerWithTimeIntervalTargetSelectorUserInfoRepeats(0.5, target, 'selftest:', null, false);
else ticker = $.NSTimer.scheduledTimerWithTimeIntervalTargetSelectorUserInfoRepeats(5, target, 'tick:', null, true);

app.run;
`;
}

/** The Windows notification-area host, as PowerShell source. */
export function windowsTrayScript(config) {
  return `# Checkarr tray icon. Generated by scripts/lib/tray.mjs - do not edit.
$ErrorActionPreference = 'Continue'
$Label = ${psQuote(config.label)}
$Url = ${psQuote(config.url)}
$Node = ${psQuote(config.node)}
$Launch = ${psQuote(config.launch)}
$ServerPidFile = ${psQuote(config.pidFile)}
$TrayPidFile = ${psQuote(config.trayPidFile)}
$LogFile = ${psQuote(config.logFile)}
$ServerLog = ${psQuote(config.serverLog)}
$IconPng = ${psQuote(config.iconFile)}

function Write-TrayLog([string]$Message) {
  try { Add-Content -Path $LogFile -Value ('[{0}] {1}' -f (Get-Date -Format 'yyyy-MM-dd HH:mm:ss'), $Message) } catch { }
}

# One tray per session: a live recorded pid means another icon is up already.
if (Test-Path $TrayPidFile) {
  $other = 0
  $raw = Get-Content $TrayPidFile -ErrorAction SilentlyContinue | Select-Object -First 1
  if ([int]::TryParse($raw, [ref]$other) -and (Get-Process -Id $other -ErrorAction SilentlyContinue)) { exit 0 }
}
Set-Content -Path $TrayPidFile -Value $PID

function Get-ServerPid {
  if (-not (Test-Path $ServerPidFile)) { return 0 }
  $raw = Get-Content $ServerPidFile -ErrorAction SilentlyContinue | Select-Object -First 1
  $serverPid = 0
  if ([int]::TryParse($raw, [ref]$serverPid) -and (Get-Process -Id $serverPid -ErrorAction SilentlyContinue)) { return $serverPid }
  return 0
}

function Open-Checkarr {
  if ((Get-ServerPid) -gt 0) {
    Start-Process $Url
  } else {
    Write-TrayLog 'server is stopped - launching it'
    Start-Process -FilePath $Node -ArgumentList ('"' + $Launch + '"') -WindowStyle Hidden
  }
}

function Stop-Checkarr {
  $serverPid = Get-ServerPid
  if ($serverPid -gt 0) {
    Write-TrayLog ("stopping server (pid $serverPid)")
    Stop-Process -Id $serverPid -Force -ErrorAction SilentlyContinue
  }
  Remove-Item $ServerPidFile -ErrorAction SilentlyContinue
  Remove-Item $TrayPidFile -ErrorAction SilentlyContinue
  $notify.Visible = $false
  $notify.Dispose()
  [System.Windows.Forms.Application]::Exit()
}

try {
  Add-Type -AssemblyName System.Windows.Forms
  Add-Type -AssemblyName System.Drawing

  $notify = New-Object System.Windows.Forms.NotifyIcon
  $notify.Text = "$Label - running"
  $notify.Icon = [System.Drawing.SystemIcons]::Application
  try {
    if (Test-Path $IconPng) {
      # System.Drawing.Icon cannot be trusted with PNG-compressed .ico entries,
      # so build the HICON from the PNG that ships beside this script.
      $bytes = [System.IO.File]::ReadAllBytes($IconPng)
      $stream = New-Object System.IO.MemoryStream(,$bytes)
      $image = [System.Drawing.Image]::FromStream($stream)
      $notify.Icon = [System.Drawing.Icon]::FromHandle($image.GetHicon())
    }
  } catch {
    Write-TrayLog ('icon load failed: ' + $_.Exception.Message)
  }

  $menu = New-Object System.Windows.Forms.ContextMenuStrip
  $itemOpen = $menu.Items.Add("Open $Label")
  $itemLog = $menu.Items.Add('Open log')
  [void]$menu.Items.Add('-')
  $itemStop = $menu.Items.Add("Stop $Label")
  $notify.ContextMenuStrip = $menu

  $itemOpen.add_Click({ try { Open-Checkarr } catch { Write-TrayLog ('open failed: ' + $_.Exception.Message) } })
  $notify.add_MouseDoubleClick({ try { Open-Checkarr } catch { Write-TrayLog ('open failed: ' + $_.Exception.Message) } })
  $itemLog.add_Click({ try { Start-Process $ServerLog } catch { } })
  $itemStop.add_Click({ try { Stop-Checkarr } catch { } })

  $timer = New-Object System.Windows.Forms.Timer
  $timer.Interval = 5000
  $timer.add_Tick({
    try { $notify.Text = if ((Get-ServerPid) -gt 0) { "$Label - running" } else { "$Label - stopped" } } catch { }
  })
  $timer.Start()

  $notify.Visible = $true
  Write-TrayLog 'tray started'
  [System.Windows.Forms.Application]::Run()
} catch {
  Write-TrayLog ('tray failed: ' + $_.Exception.Message)
  exit 1
}
`;
}

/** The hidden launcher that starts the PowerShell host without a console. */
export function windowsTrayLauncher(scriptFile) {
  const command = `powershell.exe -NoProfile -ExecutionPolicy Bypass -WindowStyle Hidden -File "${scriptFile}"`;
  return [
    "' Hidden launcher for the Checkarr tray icon. Generated by scripts/lib/tray.mjs.",
    `CreateObject("WScript.Shell").Run "${command.replace(/"/g, '""')}", 0, False`,
    ""
  ].join("\r\n");
}

/** The yad status-notifier invocation used on Linux. */
export function linuxTrayInvocation(config) {
  const open = `${shellQuote(config.node)} ${shellQuote(config.launch)}`;
  const log = `${shellQuote(config.opener)} ${shellQuote(config.serverLog)}`;
  const stop = `${shellQuote(config.node)} ${shellQuote(config.stop)}`;
  return {
    cmd: "yad",
    args: [
      "--notification",
      `--image=${config.iconFile}`,
      `--text=${config.label}`,
      `--command=${open}`,
      `--menu=Open ${config.label}!${open}|Open log!${log}|Stop ${config.label}!${stop}`
    ]
  };
}

/** The command line of a pid, or "" when it cannot be determined. */
export function defaultCommandOf(pid) {
  try {
    if (process.platform === "win32") {
      return execSync(
        "powershell -NoProfile -Command \"(Get-CimInstance Win32_Process -Filter 'ProcessId=" +
          pid +
          "').CommandLine\"",
        { encoding: "utf8", windowsHide: true }
      ).trim();
    }
    return execSync("ps -p " + pid + " -o command=", { encoding: "utf8" }).trim();
  } catch {
    return "";
  }
}

/** True when a pid is alive, judged through the injected kill. */
function isAlive(pid, kill) {
  try {
    kill(pid, 0);
    return true;
  } catch {
    return false;
  }
}

/**
 * A command we cannot read counts as ours: refusing to touch a live tray
 * beats killing something that merely reused the pid. The marker keeps an
 * unrelated process that happens to own a recycled pid safe.
 */
const isTrayCommand = (command) => command === "" || command.toLowerCase().includes(TRAY_MARKER);

export function readTrayPid(paths) {
  try {
    const pid = Number(fs.readFileSync(paths.pidFile, "utf8").trim());
    return Number.isInteger(pid) && pid > 0 ? pid : null;
  } catch {
    return null;
  }
}

/**
 * Start the tray host for this checkout unless one is already running.
 * Returns { started, pid, target, reason } - the icon is a convenience, so
 * callers should log a failure and carry on rather than exit.
 */
export async function ensureTray(options = {}) {
  const platform = options.platform ?? process.platform;
  const root = options.root ?? rootFromHere();
  const paths = options.paths ?? trayPaths({ platform, home: options.home, env: options.env, root });
  const spawnImpl = options.spawnImpl ?? spawn;
  const commandOf = options.commandOf ?? defaultCommandOf;
  const hasCommand = options.hasCommand ?? defaultHasCommand;
  const sleep = options.sleep ?? ((ms) => new Promise((resolve) => setTimeout(resolve, ms)));

  const existing = readTrayPid(paths);
  if (existing && isAlive(existing, options.kill ?? process.kill) && isTrayCommand(commandOf(existing))) {
    return {
      platform,
      started: false,
      pid: existing,
      target: paths.scriptFile ?? paths.pidFile,
      reason: "already running"
    };
  }

  ensureLog(paths.logFile);
  fs.rmSync(paths.pidFile, { force: true });

  const base = {
    label: options.label ?? APP_NAME,
    url: options.url ?? "http://127.0.0.1:5656",
    node: options.node ?? process.execPath,
    root,
    launch: path.join(root, "scripts", "launch.mjs"),
    stop: path.join(root, "scripts", "stop.mjs"),
    pidFile: path.join(root, "data", "checkarr.pid"),
    trayPidFile: paths.pidFile,
    logFile: paths.logFile,
    serverLog: path.join(root, "data", "server.log"),
    iconFile: paths.iconFile
  };

  // stdout/stderr go to the tray log: a Finder- or terminal-less launch has
  // nowhere else to report a broken icon, and osascript is chatty on errors.
  const out = fs.openSync(paths.logFile, "a");
  const detached = (cmd, args, extra = {}) => {
    const child = spawnImpl(cmd, args, { detached: true, stdio: ["ignore", out, out], ...extra });
    // A missing host (osascript/wscript/yad) must not take the server down
    // with an unhandled 'error' event; the pid check above reports the truth.
    child.on?.("error", () => {});
    child.unref();
    return child;
  };

  try {
    if (platform === "darwin") {
      writeIfChanged(paths.iconFile, encodePng(renderGlyph(36), 36));
      writeIfChanged(paths.scriptFile, macTrayScript(base));
      const child = detached("osascript", ["-l", "JavaScript", paths.scriptFile]);
      if (!child.pid)
        return {
          platform,
          started: false,
          target: paths.scriptFile,
          reason: "the menu-bar host did not start"
        };
      fs.writeFileSync(paths.pidFile, String(child.pid));
      return { platform, started: true, pid: child.pid, target: paths.scriptFile };
    }

    if (platform === "win32") {
      writeIfChanged(paths.iconFile, encodePng(renderGlyph(32), 32));
      writeIfChanged(paths.scriptFile, windowsTrayScript(base));
      writeIfChanged(paths.launcherFile, windowsTrayLauncher(paths.scriptFile));
      // The PowerShell host records its own pid and wscript exits immediately,
      // so wait for that pid before claiming an icon exists: a blocked script
      // (ExecutionPolicy, antivirus) must fail loudly, not silently.
      detached("wscript.exe", [paths.launcherFile], { windowsHide: true });
      let pid = null;
      for (let attempt = 0; attempt < 50 && !pid; attempt++) {
        await sleep(100);
        pid = readTrayPid(paths);
      }
      if (!pid) {
        return {
          platform,
          started: false,
          target: paths.scriptFile,
          reason: `the notification-area host did not start - see ${paths.logFile}`
        };
      }
      return { platform, started: true, pid, target: paths.scriptFile };
    }

    if (!hasCommand("yad")) {
      return {
        platform,
        started: false,
        target: paths.pidFile,
        reason: "yad is not installed - tray icon skipped (install yad for one)"
      };
    }
    writeIfChanged(paths.iconFile, encodePng(renderGlyph(48), 48));
    const { cmd, args } = linuxTrayInvocation({ ...base, opener: "xdg-open" });
    const child = detached(cmd, args);
    if (!child.pid)
      return {
        platform,
        started: false,
        target: paths.iconFile,
        reason: "the status-notifier host did not start"
      };
    fs.writeFileSync(paths.pidFile, String(child.pid));
    return { platform, started: true, pid: child.pid, target: paths.iconFile };
  } finally {
    fs.closeSync(out);
  }
}

/** Stop the tray host for this checkout, if it is still ours. */
export async function stopTray(options = {}) {
  const platform = options.platform ?? process.platform;
  const root = options.root ?? rootFromHere();
  const paths = trayPaths({ platform, home: options.home, env: options.env, root });
  const kill = options.kill ?? ((pid, signal) => process.kill(pid, signal));
  const commandOf = options.commandOf ?? defaultCommandOf;
  const sleep = options.sleep ?? ((ms) => new Promise((resolve) => setTimeout(resolve, ms)));

  const pid = readTrayPid(paths);
  if (!pid || !isAlive(pid, kill) || !isTrayCommand(commandOf(pid))) {
    fs.rmSync(paths.pidFile, { force: true });
    return { platform, stopped: false };
  }

  try {
    kill(pid, "SIGTERM");
  } catch {}
  for (let i = 0; i < 25 && isAlive(pid, kill); i++) await sleep(200);
  if (isAlive(pid, kill)) {
    try {
      kill(pid, "SIGKILL");
    } catch {}
  }
  fs.rmSync(paths.pidFile, { force: true });
  return { platform, stopped: true, pid };
}

function defaultHasCommand(name) {
  try {
    execFileSync("which", [name], { stdio: "ignore" });
    return true;
  } catch {
    return false;
  }
}
